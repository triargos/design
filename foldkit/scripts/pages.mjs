import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const pagesDir = fileURLToPath(new URL('../src/pages/', import.meta.url));
const outFile = fileURLToPath(new URL('../src/pages.generated.ts', import.meta.url));

const pascal = (slug) =>
  slug
    .split('-')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
const camel = (slug) => {
  const name = pascal(slug);
  return name[0].toLowerCase() + name.slice(1);
};

const pages = readdirSync(pagesDir)
  .filter((file) => file.endsWith('.ts') && !file.endsWith('.test.ts'))
  .map((file) => {
    const slug = file.replace(/\.ts$/, '');
    const source = readFileSync(pagesDir + file, 'utf8');
    return {
      slug,
      tag: pascal(slug),
      field: camel(slug),
      module: `${pascal(slug)}Page`,
      hasSubscriptions: /export const subscriptions\b/.test(source),
    };
  })
  .sort((a, b) => a.slug.localeCompare(b.slug, 'en'));

const lines = [];
const push = (...items) => lines.push(...items);

push(
  '// Generated by scripts/pages.mjs from src/pages/*.ts. Do not edit.',
  "import { Option, Schema, pipe } from 'effect';",
  "import { Route, Submodel, Subscription, Update } from 'foldkit';",
  "import type { Html } from 'foldkit/html';",
  "import { defineMessageUnion } from 'foldkit/message';",
  "import { defineRouteUnion, literal } from 'foldkit/route';",
  "import { modifyFields } from 'foldkit/struct';",
  '',
  "import { homeView, notFoundView } from './home.ts';",
  "import type { PageContext } from './pageContext.ts';",
  ...pages.map((page) => `import * as ${page.module} from './pages/${page.slug}.ts';`),
  '',
  'export const AppRoute = defineRouteUnion({',
  '  Home: {},',
  ...pages.map((page) => `  ${page.tag}: {},`),
  '  NotFound: { path: Schema.String },',
  '});',
  'export type AppRoute = typeof AppRoute.Type;',
  '',
  'const homeRouter = pipe(Route.root, Route.mapTo(AppRoute.Home));',
  ...pages.map(
    (page) => `const ${page.field}Router = pipe(literal('${page.slug}'), Route.mapTo(AppRoute.${page.tag}));`,
  ),
  '',
  'const routeParser = Route.oneOf(',
  ...pages.map((page) => `  ${page.field}Router,`),
  '  homeRouter,',
  ');',
  '',
  'export const urlToAppRoute = Route.parseUrlWithFallback(routeParser, AppRoute.NotFound);',
  '',
  'export type NavItem = Readonly<{ title: string; description: string; href: string; routeTag: AppRoute["_tag"] }>;',
  '',
  'export const NAV_ITEMS: ReadonlyArray<NavItem> = [',
  ...pages.map(
    (page) =>
      `  { title: ${page.module}.title, description: ${page.module}.description, href: ${page.field}Router(), routeTag: '${page.tag}' },`,
  ),
  '];',
  '',
  'export const homeHref = homeRouter();',
  '',
  'export const Model = Schema.Struct({',
  ...pages.map((page) => `  ${page.field}: ${page.module}.Model,`),
  '});',
  'export type Model = typeof Model.Type;',
  '',
  'export const Message = defineMessageUnion({',
  ...pages.map((page) => `  Got${page.tag}PageMessage: { message: ${page.module}.Message },`),
  '});',
  'export type Message = typeof Message.Type;',
  '',
  'export const init = (context: PageContext): Update.Return<Model, Message> =>',
  '  Update.foldChildInits(',
  '    {',
  ...pages.map((page) => `      ${page.field}: ${page.module}.init(context),`),
  '    },',
  '    {',
  '      toParentModel: (models) => models,',
  '      folds: {',
  ...pages.map(
    (page) =>
      `        ${page.field}: { toParentMessage: (message) => Message.Got${page.tag}PageMessage({ message }) },`,
  ),
  '      },',
  '    },',
  '  );',
  '',
  ...pages.flatMap((page) => [
    `const fold${page.tag}Page = Update.foldChild({`,
    `  update: ${page.module}.update,`,
    `  read: (model: Model) => Option.some(model.${page.field}),`,
    `  write: (model, next${page.tag}) => modifyFields(model, { ${page.field}: () => next${page.tag} }),`,
    `  toParentMessage: (message) => Message.Got${page.tag}PageMessage({ message }),`,
    '});',
    '',
  ]),
  'export const update = (model: Model, message: Message) =>',
  '  Message.match<Update.Return<Model, Message>>(message, {',
  ...pages.map((page) => `    Got${page.tag}PageMessage: ({ message }) => fold${page.tag}Page(model, message),`),
  '  });',
  '',
  'export const view = Submodel.defineView<Model, Message, Readonly<{ route: AppRoute }>>(',
  '  (model, { route }, h): Html =>',
  '    AppRoute.match<Html>(route, {',
  '      Home: () => homeView(NAV_ITEMS, h),',
  '      NotFound: ({ path }) => notFoundView(path, h),',
  ...pages.flatMap((page) => [
    `      ${page.tag}: () =>`,
    '        h.submodel({',
    `          slotId: '${page.slug}',`,
    `          model: model.${page.field},`,
    `          view: ${page.module}.view,`,
    `          toParentMessage: (message) => Message.Got${page.tag}PageMessage({ message }),`,
    '        }),',
  ]),
  '    }),',
  ');',
  '',
);

const withSubscriptions = pages.filter((page) => page.hasSubscriptions);
if (withSubscriptions.length === 0) {
  push('export const subscriptions = Subscription.aggregate<Model, Message>()();');
} else {
  push(
    'export const subscriptions = Subscription.aggregate(',
    ...withSubscriptions.flatMap((page) => [
      `  Subscription.lift(${page.module}.subscriptions)<Model, Message>({`,
      `    read: (model) => Option.some(model.${page.field}),`,
      `    toParentMessage: (message) => Message.Got${page.tag}PageMessage({ message }),`,
      '  }),',
    ]),
    ');',
  );
}

writeFileSync(outFile, lines.join('\n') + '\n');
console.log(`Wrote ${pages.length} pages to src/pages.generated.ts`);
