import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const srcDir = fileURLToPath(new URL('../src/', import.meta.url));
const outFile = join(srcDir, 'pavo/icons.generated.ts');
const tablerDir = fileURLToPath(new URL('../node_modules/@tabler/icons/', import.meta.url));
const nodes = JSON.parse(readFileSync(join(tablerDir, 'tabler-nodes-outline.json'), 'utf8'));

const sourceFiles = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) return sourceFiles(path);
    return path.endsWith('.ts') && !path.endsWith('.generated.ts') ? [path] : [];
  });

const names = new Set();
for (const file of sourceFiles(srcDir)) {
  for (const match of readFileSync(file, 'utf8').matchAll(/\bicon\(\s*'([a-z0-9-]+)'/g)) names.add(match[1]);
}

const unknown = [...names].filter((name) => !(name in nodes));
if (unknown.length > 0) throw new Error(`Unknown Tabler icons: ${unknown.join(', ')}`);

const entries = [...names].sort().map((name) => `  '${name}': ${JSON.stringify(nodes[name])},`);
writeFileSync(
  outFile,
  [
    '// Generated by scripts/icons.mjs from the icon(...) calls in src. Do not edit.',
    'export const ICON_NODES = {',
    ...entries,
    '} as const;',
    '',
  ].join('\n'),
);
console.log(`Wrote ${names.size} icons to src/pavo/icons.generated.ts`);
